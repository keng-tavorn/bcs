// Writes src/server/db/relations.generated.ts from prisma/schema.prisma: for every model, its relation fields
// and the model each one points to. The tenant guard (src/server/db/tenant.ts) follows include/select/where/
// orderBy through this map; tests/generated/tenant-isolation.test.ts fails when the file is out of date.
// Run by `pnpm db:migrate` after `prisma generate`, or directly: pnpm exec tsx scripts/gen-db-relations.ts
import { readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import internals from '@prisma/internals'

export const RELATIONS_FILE = 'src/server/db/relations.generated.ts'

type DmmfField = { name: string; kind: string; type: string; isList: boolean }
type DmmfModel = { name: string; fields: DmmfField[] }

export async function renderRelations(root: string): Promise<string> {
  const dmmf = await internals.getDMMF({ datamodel: readFileSync(path.join(root, 'prisma/schema.prisma'), 'utf8') })
  const models = [...(dmmf.datamodel.models as unknown as DmmfModel[])].sort((a, b) => a.name.localeCompare(b.name))
  const lines = models.map((m) => {
    const rels = m.fields
      .filter((f) => f.kind === 'object')
      .sort((a, b) => a.name.localeCompare(b.name))
      .map((f) => `    ${f.name}: { model: '${f.type}', list: ${f.isList} },`)
    return rels.length ? `  ${m.name}: {\n${rels.join('\n')}\n  },` : `  ${m.name}: {},`
  })
  return [
    '// Generated by scripts/gen-db-relations.ts from prisma/schema.prisma — do not edit by hand.',
    '// Used by the tenant guard (tenant.ts) to follow relations; tests/generated checks that it is current.',
    '',
    'export interface RelationTarget {',
    '  readonly model: string',
    '  readonly list: boolean',
    '}',
    '',
    'export const RELATIONS: Readonly<Record<string, Readonly<Record<string, RelationTarget>>>> = {',
    ...lines,
    '}',
    '',
  ].join('\n')
}

if (process.argv[1] && path.resolve(process.argv[1]) === path.resolve(import.meta.filename)) {
  const root = process.cwd()
  writeFileSync(path.join(root, RELATIONS_FILE), await renderRelations(root))
  console.log(`wrote ${RELATIONS_FILE}`)
}
