def _items():
    r = rng('items')
    out = []
    for prefix, cat, service, acc, rows in _ITEMS:
        for i, (name, unit, price) in enumerate(rows, 1):
            item = {'code': f'{prefix}-{i:03d}', 'nameTh': name, 'unit': unit, 'refUnitPrice': price, 'category': cat,
                    'isService': service, 'accountCode': acc, 'whtIncomeType': WHT.get(cat) if service == 'Y' else None,
                    'agreementSupplier': None, 'agreedUnitPrice': None, 'agreementNote': None}
            # about one item in four has an annual price agreement with one supplier (guided buying, FR-INT-102)
            if cat in ('MAT', 'STEEL', 'RMC', 'SAFETY', 'OFFICE', 'FUEL') and r.random() < 0.45:
                item['agreementSupplier'] = r.choice([c for c in SUPPLIERS_BY_CAT[cat] if c not in INACTIVE])
                p = str(price)
                item['agreedUnitPrice'] = p if '.' in p else int(int(p) * r.choice((96, 97, 98)) / 100)
                item['agreementNote'] = 'ราคาตกลงรายปี (สังเคราะห์) · ใช้กับแคตตาล็อกราคาที่ตกลง FR-INT-102'
            out.append(item)
    return out


