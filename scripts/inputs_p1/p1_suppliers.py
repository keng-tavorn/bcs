def _build():
    r = rng('suppliers')
    stems = list(_STEMS)
    r.shuffle(stems)
    used_names, sup, pay = set(), [], []
    serial_j, serial_i = 1000, 2000
    n = 0
    for cat, catname, count, kind in CATEGORIES:
        for k in range(count):
            n += 1
            code = f'SP{n:04d}'
            if kind == 'I':
                serial_i += 1
                person = f'{r.choice(_FIRST)} {r.choice(_LAST)}'
                while person in used_names:
                    person = f'{r.choice(_FIRST)} {r.choice(_LAST)}'
                used_names.add(person)
                name = f'นาย{person} ({r.choice(_TRADE)} รับเหมารายย่อย)'
                tax, vat, payee = taxid(f'3999998{serial_i:05d}'), 'N', 'INDIVIDUAL'
                acct_name = f'นาย{person}'
            else:
                serial_j += 1
                while True:
                    stem = stems[(n * 7 + k) % len(stems)] if r.random() < 0.5 else r.choice(stems)
                    base = f'{stem}{r.choice(_SUFFIX[cat])}'
                    if base not in used_names:
                        break
                used_names.add(base)
                partnership = (kind == 'P' and r.random() < 0.6) or (kind == 'J' and r.random() < 0.12)
                name = f'ห้างหุ้นส่วนจำกัด {base}' if partnership else f'บริษัท {base} จำกัด'
                small = partnership and r.random() < 0.45
                tax, vat, payee = taxid(f'0999998{serial_j:05d}'), 'N' if small else 'Y', 'JURISTIC'
                acct_name = name
            sup.append({'code': code, 'nameTh': name, 'taxId': tax, 'branchCode': '00000', 'vatRegistered': vat,
                        'email': f'{code.lower()}@supplier.simec.local', 'phone': f'02-000-{n + 1000:04d}', 'category': catname,
                        'expressVendorCode': f'V{n + 1000:04d}', '_cat': cat})
            bank = r.choice(['004', '014', '002', '006', '025', '011', '004', '014'])
            acct = f'9{r.randrange(10 ** 8, 10 ** 9):09d}'
            etax = 'FULL' if cat in ETAX_FULL else ('EMAIL' if vat == 'Y' and r.random() < 0.18 else 'NONE')
            pay.append({'supplierCode': code, 'payeeType': payee, 'whtIncomeType': WHT.get(cat),
                        'paymentTermDays': r.choice(TERMS[cat]), 'bankCode': bank,
                        'bankBranchTh': f'สาขา{r.choice(["บางนา", "รังสิต", "สีลม", "ลาดพร้าว", "บางกะปิ", "นนทบุรี", "ชลบุรี", "ราชบุรี"])} (สมมติ)',
                        'accountNo': f'{acct[:3]}-{acct[3]}-{acct[4:9]}-{acct[9]}', 'accountName': acct_name,
                        'eTaxIssuer': etax, 'registryStatus': 'ACTIVE', 'note': None})
    # realistic odd cases: a branch of an existing seller, two that closed down, one that left the VAT register
    big = next(s for s in sup if s['_cat'] == 'MAT')
    n += 1
    sup.append({**big, 'code': f'SP{n:04d}', 'nameTh': big['nameTh'] + ' (สาขาชลบุรี)', 'branchCode': '00003',
                'email': f'sp{n:04d}@supplier.simec.local', 'phone': f'02-000-{n + 1000:04d}', 'expressVendorCode': f'V{n + 1000:04d}'})
    pay.append({**next(p for p in pay if p['supplierCode'] == big['code']), 'supplierCode': f'SP{n:04d}',
                'note': 'สาขาของผู้ขายรายเดิม · เลขผู้เสียภาษีเดียวกัน สาขาต่างกัน (BR-IVC ใบกำกับออกโดยสาขา)'})
    vat_gone = next(s for s in sup[10:] if s['_cat'] == 'MAT' and s['vatRegistered'] == 'Y')
    for code, status, note in ((sup[30]['code'], 'CEASED', 'เลิกกิจการแล้ว · ใช้ทดสอบคำเตือนตอนออก PO และรอบจ่าย (BR-SUP-04 FR-PAY-101)'),
                               (sup[95]['code'], 'CEASED', 'เลิกกิจการแล้ว'),
                               (vat_gone['code'], 'VAT_CANCELLED', 'สรรพากรแจ้งว่าออกจากระบบ VAT แล้ว แต่ทะเบียนผู้ขายยังเป็น Y (ข้อมูลเก่า) · ใบกำกับใหม่ต้องไม่มี VAT')):
        p = next(p for p in pay if p['supplierCode'] == code)
        p['registryStatus'], p['note'] = status, note
    return sup, pay


