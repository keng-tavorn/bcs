// Pure parts of the database gate (spec §6.3, §15.5 gate 5), kept apart from scripts/verify-db.ts so they have
// unit tests. Inputs are rows read from the Postgres catalogs.

/** Tables whose rows are never updated or deleted (INV-EVT-01), each guarded by a bcs_forbid_mutation trigger. */
export const APPEND_ONLY = ['Event', 'BudgetLedgerEntry', 'EventSeal', 'AiCreditLedger'] as const

// Tables finish line A needs (spec §16.10), checked with --strict. EventSeal belongs to S5-14 [go-live]:
// "seal audit" is in the list of things a demo build may skip.
export const STRICT_TABLES = ['Event', 'BudgetLedgerEntry', 'BudgetLineBalance', 'RequestLine', 'PositionAssignment', 'DoaVersion'] as const
export const STRICT_OPTIONAL_TABLES: Record<string, string> = {
  EventSeal: 'seal audit เป็นข้อ S5-14 [go-live] และข้ามได้ใน demo (§16.10)',
}

export function strictTableProblems(tables: ReadonlySet<string>): { problems: string[]; notes: string[] } {
  const problems = STRICT_TABLES.filter((t) => !tables.has(t)).map((t) => `ตาราง "${t}" ยังไม่มี (โหมด strict: เส้นชัย A ต้องมี)`)
  const notes = Object.entries(STRICT_OPTIONAL_TABLES)
    .filter(([t]) => !tables.has(t))
    .map(([t, why]) => `ตาราง "${t}" ยังไม่มี — อนุญาต: ${why}`)
  return { problems, notes }
}

export interface ForeignKeyRow {
  name: string
  fromTable: string
  toTable: string
  fromColumns: string[]
  toColumns: string[]
}

/**
 * A foreign key between two tables that both carry organizationId must include organizationId on both sides,
 * in the same position, so a row can never point at another tenant's row (INV-TEN-01 enforced by the database).
 */
export function orgForeignKeyProblems(fks: readonly ForeignKeyRow[], orgTables: ReadonlySet<string>): string[] {
  const problems: string[] = []
  for (const fk of fks) {
    if (!orgTables.has(fk.fromTable) || !orgTables.has(fk.toTable)) continue
    const paired = fk.fromColumns.some((c, i) => c === 'organizationId' && fk.toColumns[i] === 'organizationId')
    if (!paired) {
      problems.push(
        `foreign key ${fk.name}: "${fk.fromTable}"(${fk.fromColumns.join(', ')}) → "${fk.toTable}"(${fk.toColumns.join(', ')}) ไม่รวม organizationId ทั้งสองฝั่ง — แถวอ้างข้อมูลของ tenant อื่นได้`,
      )
    }
  }
  return problems
}

export interface TriggerRow {
  name: string
  functionName: string
  /** pg_trigger.tgtype bit mask */
  type: number
  /** pg_trigger.tgenabled: O = enabled, D = disabled, R = replica only, A = always */
  enabled: string
  /** true when the trigger has a WHEN condition */
  hasCondition: boolean
}

const TRIGGER_ROW = 1
const TRIGGER_BEFORE = 2
const TRIGGER_INSERT = 4
const TRIGGER_DELETE = 8
const TRIGGER_UPDATE = 16
const ENABLED = new Set(['O', 'A'])

/** Problems with the append-only trigger of one table: it must exist, fire BEFORE UPDATE OR DELETE for each row, unconditionally, and be enabled. */
export function appendOnlyTriggerProblems(table: string, triggers: readonly TriggerRow[]): string[] {
  const candidates = triggers.filter((t) => t.functionName === 'bcs_forbid_mutation')
  const good = candidates.filter(
    (t) =>
      (t.type & TRIGGER_ROW) !== 0 &&
      (t.type & TRIGGER_BEFORE) !== 0 &&
      (t.type & TRIGGER_UPDATE) !== 0 &&
      (t.type & TRIGGER_DELETE) !== 0 &&
      !t.hasCondition &&
      ENABLED.has(t.enabled),
  )
  if (good.length) return []
  if (candidates.length === 0) return [`ตาราง ${table} ไม่มี trigger append-only (BEFORE UPDATE OR DELETE FOR EACH ROW → bcs_forbid_mutation)`]
  return candidates.map((t) => {
    if (!ENABLED.has(t.enabled)) return `trigger ${t.name} บน ${table} ถูกปิด (tgenabled = ${t.enabled}) — ต้อง ENABLE`
    if (t.hasCondition) return `trigger ${t.name} บน ${table} มีเงื่อนไข WHEN — ต้องทำงานกับทุกแถว`
    return `trigger ${t.name} บน ${table} ต้องเป็น BEFORE UPDATE OR DELETE FOR EACH ROW`
  })
}

/**
 * "Event".seq is the global order of the audit trail, used to sort and seal it (§4.5 field table): it must be
 * GENERATED ALWAYS AS IDENTITY (pg_attribute.attidentity = 'a'), so no insert can choose its own place.
 */
export function eventSeqProblems(identity: string | undefined): string[] {
  if (identity === 'a') return []
  const now = identity === 'd' ? 'GENERATED BY DEFAULT (ผู้ insert กำหนดค่าเองได้)' : 'ไม่ใช่ identity'
  return [`"Event".seq ต้องเป็น GENERATED ALWAYS AS IDENTITY — ลำดับรวมทั้งระบบที่ฐานข้อมูลกำหนด ใช้เรียงและ seal (§4.5) แต่ตอนนี้${now}`]
}

/** The Event insert-time stamp (createdAt from the database clock) must exist and fire BEFORE INSERT for each row. */
export function stampTriggerProblems(triggers: readonly TriggerRow[]): string[] {
  const t = triggers.find((x) => x.name === 'Event_stamp_created_at')
  if (!t) return ['ไม่มี trigger "Event_stamp_created_at" บน "Event" (createdAt ต้องมาจากนาฬิกาของฐานข้อมูล)']
  const problems: string[] = []
  if (t.functionName !== 'bcs_stamp_created_at') problems.push(`trigger "Event_stamp_created_at" เรียก ${t.functionName} แทน bcs_stamp_created_at`)
  if ((t.type & TRIGGER_ROW) === 0 || (t.type & TRIGGER_BEFORE) === 0 || (t.type & TRIGGER_INSERT) === 0) {
    problems.push('trigger "Event_stamp_created_at" ต้องเป็น BEFORE INSERT FOR EACH ROW')
  }
  if (t.hasCondition) problems.push('trigger "Event_stamp_created_at" มีเงื่อนไข WHEN — ต้องทำงานกับทุกแถว')
  if (!ENABLED.has(t.enabled)) problems.push(`trigger "Event_stamp_created_at" ถูกปิด (tgenabled = ${t.enabled})`)
  return problems
}

export interface ColumnRow {
  name: string
  /** format_type() of the column */
  type: string
  notNull: boolean
  hasDefault: boolean
  identity: string
  generated: string
  /** first label when the column is an enum, else null */
  enumLabel: string | null
}

const quoteLiteral = (s: string) => `'${s.replace(/'/g, "''")}'`

/**
 * SQL for a value of `column` in a throw-away probe row (the verify database is rolled back afterwards).
 * Columns that are nullable, defaulted, identity or generated are left out (null). Throws on a type it cannot fill.
 */
export function probeValueSql(column: ColumnRow): string | null {
  if (column.identity || column.generated || column.hasDefault || !column.notNull) return null
  const t = column.type
  if (column.enumLabel !== null) return `${quoteLiteral(column.enumLabel)}::${t}`
  if (t.endsWith('[]')) return `'{}'::${t}`
  if (t === 'uuid') return 'gen_random_uuid()'
  if (t === 'text' || t.startsWith('character') || t === 'citext' || t === 'name') return `'p'::${t}`
  if (/^(smallint|integer|bigint|numeric|real|double precision)/.test(t)) return `1::${t}`
  if (t === 'boolean') return 'false'
  if (/^(timestamp|date|time)/.test(t)) return `now()::${t}`
  if (t === 'json' || t === 'jsonb') return `'{}'::${t}`
  if (t === 'bytea') return `'\\x00'::bytea`
  if (t === 'interval') return `'1 day'::interval`
  if (/range$/.test(t)) return `'empty'::${t}`
  throw new Error(`สร้างค่าทดสอบให้คอลัมน์ ${column.name} ชนิด ${t} ไม่ได้ — เพิ่มชนิดนี้ใน probeValueSql (scripts/lib/db-checks.ts)`)
}
