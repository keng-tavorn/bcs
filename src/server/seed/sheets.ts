const text = z.string().trim().min(1)
/** A department code as the organization screens take it (src/server/services/org-structure): e.g. HRA-GA */
const departmentCode = z.string().regex(/^[A-Z0-9][A-Z0-9_-]{0,39}$/)
/** A whole number or empty; z.coerce would read an empty cell as 0 */
const intOrNull = (max: number) =>
  z
    .string()
    .nullable()
    .transform((v, ctx) => {
      if (v === null) return null
      if (!/^\d+$/.test(v) || Number(v) > max) {
        ctx.addIssue({ code: 'custom', message: `not a whole number up to ${max}: ${v}` })
        return z.NEVER
      }
      return Number(v)
    })
const yesNo = z.enum(['Y', 'N']).transform((v) => v === 'Y')
/** Whole baht written as a number in the sheet ("20000") or empty; DOA amounts in the sheet have no satang */
const bahtOrNull = z
  .string()
  .nullable()
  .transform((v, ctx) => {
    if (v === null) return null
    if (!/^\d+(\.\d{1,2})?$/.test(v)) {
      ctx.addIssue({ code: 'custom', message: `not an amount in baht: ${v}` })
      return z.NEVER
    }
    return amountToSatang(v)
  })

function issueText(error: z.ZodError): string {
  return error.issues.map((i) => `${i.path.join('.') || '(row)'}: ${i.message}`).join('; ')
}

function rows<T>(workbook: InputWorkbook, sheet: string, schema: z.ZodType<T>): T[] {
  return workbook.table(sheet).map(({ row, values }) => {
    const parsed = schema.safeParse(values)
    if (!parsed.success) throw new Error(`${sheet} row ${row}: ${issueText(parsed.error)}`)
    return parsed.data
  })
}

