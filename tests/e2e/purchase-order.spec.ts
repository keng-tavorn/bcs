  await topShot(requester, testInfo, 'po-requester')
  await requester.goto('/procurement/pos')
  await expect(requester.getByText('หน้านี้สำหรับฝ่ายจัดซื้อ ถ้าคิดว่าควรเปิดได้ ติดต่อผู้ดูแลระบบขององค์กร')).toBeVisible()
